#!/usr/bin/env python3
"""
Generate (and mesh) the OpenFOAM case for one micro-structured reactor slot.

Geometry (half slot, symmetry at y = 0):

      y ^   coolant side (externalWallHeatFluxTemperature: h, Ta = coolant T)
        |   +------------------------------------------------------+
        |   |  steel plate  (region "solid")                        |
        |   +------------------------------------------------------+  <- solid/fluid interface (coupled)
        |   |  porous catalyst bed + H2/CO2 gas (region "fluid")    |
  inlet |-> |  reaction heat source: 15 axial zones (from 1-D model) |-> outlet
        |   +------------------------------------------------------+  y = 0 symmetry plane
        +------------------------------------------------------------> x (flow)
    z = slot height (3rd dimension; side walls are adiabatic)

Usage:
    python3 setup_case.py            # writes ./case and meshes it
    python3 setup_case.py --no-mesh  # only writes the dictionaries

Requires an OpenFOAM (openfoam.com / ESI) environment: blockMesh, splitMeshRegions,
topoSet, chtMultiRegionFoam on the PATH. Tested with OpenFOAM v1912; written to stay
compatible with newer ESI releases (v2306 / v2406).
"""
import argparse
import json
import math
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CASE = os.path.join(HERE, "case")
SETTINGS = os.path.join(HERE, "case_settings.json")
R = 8.314


def header(cls, obj, location=None):
    loc = '    location    "%s";\n' % location if location else ""
    return (
        "/*--------------------------------*- C++ -*----------------------------------*\\\n"
        "  Generated by setup_case.py - edit case_settings.json, not this file\n"
        "\\*---------------------------------------------------------------------------*/\n"
        "FoamFile\n{\n    version     2.0;\n    format      ascii;\n"
        "    class       %s;\n%s    object      %s;\n}\n\n" % (cls, loc, obj)
    )


def write(rel, text):
    path = os.path.join(CASE, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def sh(cmd, log):
    with open(os.path.join(CASE, log), "w") as f:
        r = subprocess.run(cmd, cwd=CASE, stdout=f, stderr=subprocess.STDOUT, shell=True)
    if r.returncode != 0:
        sys.exit("FAILED: %s (see case/%s)" % (cmd, log))


def load():
    with open(SETTINGS) as f:
        s = json.load(f)
    hp_rel = s.get("heat_profile_file", "reactor_model/heat_profile.json")   # path relative to the repo root
    hp_path = os.path.join(HERE, "..", hp_rel)
    if not os.path.exists(hp_path):
        sys.exit("heat-release profile %s missing - run reactor_model/plug_flow_model.py first" % hp_rel)
    with open(hp_path) as f:
        hp = json.load(f)
    return s, hp


# --------------------------------------------------------------------------- mesh
def block_mesh(s):
    g, m = s["geometry"], s["mesh"]
    L, hb, tw, H = g["length_m"], g["bed_half_thickness_m"], g["wall_thickness_m"], g["slot_height_m"]
    y2 = hb + tw
    v = [
        (0, 0, 0), (L, 0, 0), (L, hb, 0), (0, hb, 0),
        (0, 0, H), (L, 0, H), (L, hb, H), (0, hb, H),
        (0, y2, 0), (L, y2, 0), (L, y2, H), (0, y2, H),
    ]
    verts = "\n".join("    (%.9g %.9g %.9g)" % p for p in v)
    return header("dictionary", "blockMeshDict") + """scale 1;

vertices
(
%s
);

blocks
(
    hex (0 1 2 3 4 5 6 7)   fluid (%d %d %d) simpleGrading (1 1 1)
    hex (3 2 9 8 7 6 10 11) solid (%d %d %d) simpleGrading (1 1 1)
);

boundary
(
    inlet     { type patch;         faces ((0 4 7 3)); }
    outlet    { type patch;         faces ((1 2 6 5)); }
    symmetry  { type symmetryPlane; faces ((0 1 5 4)); }
    sideWalls { type wall;          faces ((0 3 2 1) (4 5 6 7)); }
    coolant   { type wall;          faces ((8 11 10 9)); }
    solidEnds { type wall;          faces ((3 7 11 8) (2 9 10 6) (3 8 9 2) (7 6 10 11)); }
);
""" % (verts, m["cells_x"], m["cells_bed_y"], m["cells_z"], m["cells_x"], m["cells_wall_y"], m["cells_z"])


def zone_names(s, hp):
    nz, nr = len(hp["zones"]), s["reaction"]["n_radial_bands"]
    return [("bed_%02d_%d" % (i, j), i, j) for i in range(1, nz + 1) for j in range(1, nr + 1)]


def topo_set(s, hp):
    """Heat-release zones: n_zones axial slices x n_radial_bands bands across the bed.
    Zone edges coincide with mesh faces, so every cell belongs to exactly one zone."""
    g, m = s["geometry"], s["mesh"]
    nz, nr = len(hp["zones"]), s["reaction"]["n_radial_bands"]
    if m["cells_x"] % nz or m["cells_bed_y"] % nr:
        sys.exit("cells_x must be a multiple of n_zones and cells_bed_y a multiple of n_radial_bands")
    big = 10 * max(g["bed_half_thickness_m"], g["slot_height_m"], g["length_m"])
    hb = g["bed_half_thickness_m"]
    acts = []
    for name, i, j in zone_names(s, hp):
        zn = hp["zones"][i - 1]
        x0 = -big if i == 1 else zn["x0"]
        x1 = big if i == nz else zn["x1"]
        y0 = -big if j == 1 else hb * (j - 1) / nr
        y1 = big if j == nr else hb * j / nr
        acts.append(
            "    { name %s; type cellSet; action new; source boxToCell;\n"
            "      box (%.9g %.9g %.9g) (%.9g %.9g %.9g); }" % (name, x0, y0, -big, x1, y1, big)
        )
    # one cellZone covering the whole bed, used by the porosity model
    acts.append(
        "    { name bedAll; type cellSet; action new; source boxToCell;\n"
        "      box (%.9g %.9g %.9g) (%.9g %.9g %.9g); }" % (-big, -big, -big, big, big, big)
    )
    acts.append("    { name bed; type cellZoneSet; action new; source setToCellZone; set bedAll; }")
    return header("dictionary", "topoSetDict") + "actions\n(\n%s\n);\n" % "\n".join(acts)


# --------------------------------------------------------------------------- physics
def zone_heat(s, hp, feed_scale=1.0, zone_T=None):
    """Volumetric heat release [W/m3] per zone.

    q = q_ref(x) * feed_scale * exp[-Ea/R (1/T_zone - 1/T_ref)]
    q_ref(x) comes from the 1-D model (heat_profile.json). zone_T = {name: T [K]};
    when None, T_zone = T_ref. run_pid.py updates zone_T before every chunk, so the
    Arrhenius coupling is exact and does not depend on the solver's enthalpy reference.
    """
    Tref, Ea = s["reaction"]["T_ref_K"], s["reaction"]["Ea_J_mol"]
    # reactant-depletion limit: heat can never exceed full conversion of the CO2 fed,
    # i.e. the Arrhenius multiplier is capped at 1 / X_target (prevents unbounded runaway)
    f_max = 1.0 / s["reaction"]["X_target_at_Tref"]
    out = {}
    for name, i, j in zone_names(s, hp):
        T = Tref if zone_T is None else zone_T[name]
        f = min(math.exp(-Ea / R * (1.0 / T - 1.0 / Tref)), f_max)
        out[name] = hp["zones"][i - 1]["q_W_m3"] * feed_scale * f
    return out


def fv_options(s, hp, feed_scale=1.0, zone_T=None):
    """Porosity (Ergun) + reaction heat source in every zone."""
    b = s["bed"]
    eps, dp = b["porosity"], b["particle_diameter_m"]
    d = 150.0 * (1 - eps) ** 2 / (eps ** 3 * dp ** 2)       # 1/m2 (Darcy)
    f = 2.0 * 1.75 * (1 - eps) / (eps ** 3 * dp)            # 1/m  (Forchheimer, OpenFOAM uses f/2)
    txt = header("dictionary", "fvOptions", "constant/fluid")
    txt += """porosity
{
    type            explicitPorositySource;
    explicitPorositySourceCoeffs
    {
        selectionMode   cellZone;
        cellZone        bed;
        type            DarcyForchheimer;
        d   (%.6g %.6g %.6g);
        f   (%.6g %.6g %.6g);
        coordinateSystem
        {
            origin  (0 0 0);
            rotation { type none; }
        }
    }
}
""" % (d, d, d, f, f, f)
    for name, q in zone_heat(s, hp, feed_scale, zone_T).items():
        txt += """
heat_%s
{
    type            scalarSemiImplicitSource;
    selectionMode   cellSet;
    cellSet         %s;
    volumeMode      specific;
    injectionRateSuSp
    {
        h   (%.8g 0);   // W/m3
    }
}
""" % (name, name, q)
    return txt


def thermo_fluid(s):
    gas, op = s["gas"], s["operating"]
    Pr = gas["mu_Pa_s"] * gas["Cp_J_kgK"] / gas["k_eff_W_mK"]
    return header("dictionary", "thermophysicalProperties", "constant/fluid") + """thermoType
{
    type            heRhoThermo;
    mixture         pureMixture;
    transport       const;
    thermo          hConst;
    equationOfState perfectGas;
    specie          specie;
    energy          sensibleEnthalpy;
}

mixture
{
    specie         { molWeight %.6g; }
    thermodynamics { Cp %.6g; Hf 0; }
    transport      { mu %.6g; Pr %.6g; }   // Pr set so that k = %.3g W/(m K) (effective bed conductivity)
}
""" % (op["molWeight_kg_kmol"], gas["Cp_J_kgK"], gas["mu_Pa_s"], Pr, gas["k_eff_W_mK"])


def thermo_solid(s):
    w = s["wall"]
    return header("dictionary", "thermophysicalProperties", "constant/solid") + """thermoType
{
    type            heSolidThermo;
    mixture         pureMixture;
    transport       constIso;
    thermo          hConst;
    equationOfState rhoConst;
    specie          specie;
    energy          sensibleEnthalpy;
}

mixture
{
    specie          { molWeight 56; }
    transport       { kappa %.6g; }
    thermodynamics  { Hf 0; Cp %.6g; }
    equationOfState { rho %.6g; }
}
""" % (w["k_W_mK"], w["Cp_J_kgK"], w["rho_kg_m3"])


def fields(s):
    op = s["operating"]
    T0, P, u = op["T_inlet_K"], op["P_Pa"], op["superficial_velocity_m_s"]
    Ta, h = op["coolant_T_initial_K"], op["coolant_h_W_m2K"]
    out = {}
    out["0/fluid/U"] = header("volVectorField", "U", "0/fluid") + """dimensions      [0 1 -1 0 0 0 0];
internalField   uniform (%g 0 0);
boundaryField
{
    ".*"        { type noSlip; }
    symmetry    { type symmetryPlane; }
    inlet       { type fixedValue; value uniform (%g 0 0); }
    outlet      { type inletOutlet; inletValue uniform (0 0 0); value uniform (%g 0 0); }
}
""" % (u, u, u)
    out["0/fluid/T"] = header("volScalarField", "T", "0/fluid") + """dimensions      [0 0 0 1 0 0 0];
internalField   uniform %g;
boundaryField
{
    ".*"        { type zeroGradient; }
    symmetry    { type symmetryPlane; }
    inlet       { type fixedValue; value uniform %g; }
    outlet      { type inletOutlet; inletValue uniform %g; value uniform %g; }
    fluid_to_solid
    {
        type            compressible::turbulentTemperatureCoupledBaffleMixed;
        Tnbr            T;
        kappaMethod     fluidThermo;
        value           uniform %g;
    }
}
""" % (T0, T0, T0, T0, T0)
    out["0/fluid/p_rgh"] = header("volScalarField", "p_rgh", "0/fluid") + """dimensions      [1 -1 -2 0 0 0 0];
internalField   uniform %g;
boundaryField
{
    ".*"        { type fixedFluxPressure; value uniform %g; }
    symmetry    { type symmetryPlane; }
    outlet      { type fixedValue; value uniform %g; }
}
""" % (P, P, P)
    out["0/fluid/p"] = header("volScalarField", "p", "0/fluid") + """dimensions      [1 -1 -2 0 0 0 0];
internalField   uniform %g;
boundaryField
{
    ".*"        { type calculated; value uniform %g; }
    symmetry    { type symmetryPlane; }
}
""" % (P, P)
    out["0/solid/T"] = header("volScalarField", "T", "0/solid") + """dimensions      [0 0 0 1 0 0 0];
internalField   uniform %g;
boundaryField
{
    ".*"        { type zeroGradient; }
    coolant
    {
        type            externalWallHeatFluxTemperature;
        mode            coefficient;
        Ta              uniform %g;
        h               uniform %g;
        kappaMethod     solidThermo;
        value           uniform %g;
    }
    solid_to_fluid
    {
        type            compressible::turbulentTemperatureCoupledBaffleMixed;
        Tnbr            T;
        kappaMethod     solidThermo;
        value           uniform %g;
    }
}
""" % (T0, Ta, h, T0, T0)
    out["0/solid/p"] = header("volScalarField", "p", "0/solid") + """dimensions      [1 -1 -2 0 0 0 0];
internalField   uniform %g;
boundaryField
{
    ".*"        { type calculated; value uniform %g; }
}
""" % (P, P)
    return out


