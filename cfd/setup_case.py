def control_dict(s, end_time):
    c = s["control"]
    return header("dictionary", "controlDict") + """application     chtMultiRegionFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         %g;
deltaT          0.01;
writeControl    adjustable;
writeInterval   %g;
purgeWrite      0;
writeFormat     ascii;
writePrecision  8;
writeCompression on;
timeFormat      general;
timePrecision   8;
runTimeModifiable no;
adjustTimeStep  yes;
maxCo           0.5;
maxDi           10;
maxDeltaT       0.2;
""" % (end_time, c["chunk_s"])


def main():
    global CASE, SETTINGS
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-mesh", action="store_true")
    ap.add_argument("--settings", default=SETTINGS, help="settings JSON (default case_settings.json)")
    ap.add_argument("--case", default=CASE, help="case directory to create (default ./case)")
    a = ap.parse_args()
    CASE, SETTINGS = os.path.abspath(a.case), os.path.abspath(a.settings)
    s, hp = load()

    if os.path.exists(CASE):
        shutil.rmtree(CASE)
    os.makedirs(CASE)

    write("system/blockMeshDict", block_mesh(s))
    write("system/fluid/topoSetDict", topo_set(s, hp))
    write("system/controlDict", control_dict(s, s["control"]["chunk_s"]))
    for rel, (cls, obj, body) in STATIC.items():
        write(rel, header(cls, obj) + body)
    write("constant/fluid/thermophysicalProperties", thermo_fluid(s))
    write("constant/solid/thermophysicalProperties", thermo_solid(s))
    write("constant/fluid/fvOptions", fv_options(s, hp))
    open(os.path.join(CASE, "case.foam"), "w").close()   # for ParaView
    print("case dictionaries written to", CASE)

    if a.no_mesh:
        return
    sh("blockMesh", "log.blockMesh")
    sh("splitMeshRegions -cellZones -overwrite", "log.splitMeshRegions")
    sh("topoSet -region fluid", "log.topoSet")
    for rel, txt in fields(s).items():
        write(rel, txt)
    sh("checkMesh -region fluid", "log.checkMesh.fluid")
    sh("checkMesh -region solid", "log.checkMesh.solid")
    n_f = n_s = "?"
    for reg in ("fluid", "solid"):
        for line in open(os.path.join(CASE, "log.checkMesh.%s" % reg)):
            if line.strip().startswith("cells:"):
                if reg == "fluid":
                    n_f = line.split()[-1]
                else:
                    n_s = line.split()[-1]
    print("mesh ready: fluid %s cells, solid %s cells" % (n_f, n_s))


if __name__ == "__main__":
    main()
